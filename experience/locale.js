// strings.js reads them (the game writes T.key). English is the source: what a language leaves out shows
// in English, so a language can be added a part at a time.
//
// To add a language: copy `en` under a new name, translate the values and add a line to LANGS at the bottom
// (the menu's list takes it from there). tools/langtest.html then says what is missing or does not fit.
//
// A value is a string, or a function when it takes numbers or names. Keep the function's arguments as in
// `en`; the words around them can go in any order. A card's text is a string with its numbers from
// cards.config.js: {spaces} is the number, {spaces|клетку|клетки|клеток} the word that goes with it (the
// forms the language's `plural` below takes).

// English: 1 player, 2 players
const pluralEn = (n, one, other) => (n === 1 ? one : other)
// Ukrainian and Russian: 1 гравець, 2 гравці, 5 гравців
const pluralSlavic = (n, one, few, many) => {
  const a = n % 10, b = n % 100
  return a === 1 && b !== 11 ? one : a >= 2 && a <= 4 && (b < 12 || b > 14) ? few : many
}
// Thai has one form
const pluralOne = (n, one) => one

const ord = n => n + (n % 10 === 1 && n % 100 !== 11 ? 'st' : n % 10 === 2 && n % 100 !== 12 ? 'nd' : n % 10 === 3 && n % 100 !== 13 ? 'rd' : 'th')

